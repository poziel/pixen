const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const server=require('node:child_process').spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','1477','--strictPort'],{stdio:'pipe',windowsHide:true});
 await new Promise((resolve,reject)=>{server.stdout.on('data',d=>{if(String(d).includes('Local:'))resolve()});server.on('error',reject);server.on('exit',code=>reject(new Error('Vite exited '+code)));});
 const browser=await chromium.launch({channel:'chrome',args:['--no-proxy-server']});
 try {
  const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.setDefaultTimeout(12000);
  await page.route('**/src/services/backend.ts',r=>r.fulfill({contentType:'text/javascript',body:fs.readFileSync('scripts/fixtures/manual-tools.js','utf8').replace('let opened=false','let opened=true').replace('revision=0','revision=1')}));
  await page.route('**/@tauri-apps_api_window.js*',r=>r.fulfill({contentType:'text/javascript',body:'export function getCurrentWindow(){return {onDragDropEvent:async()=>()=>{},onCloseRequested:async cb=>{window.testQuit=()=>cb({preventDefault(){}});return ()=>{}},close:async()=>{window.testClosed=true}}}'}));
  await page.route('**/@tauri-apps_api_event.js*',r=>r.fulfill({contentType:'text/javascript',body:'export async function listen(){return ()=>{}}'}));
  await page.goto('http://127.0.0.1:1477');
  await page.locator('canvas.artwork').waitFor();
  await page.keyboard.press('Control+1');
  const sidebar=page.locator('#side-panel');await sidebar.waitFor();
  const box=await sidebar.boundingBox();
  await page.mouse.move(box.x+box.width+2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(700,box.y+box.height/2,{steps:10});await page.mouse.up();
  assert((await page.locator('.color-picker').boundingBox()).width<=340);
  const wide=await sidebar.boundingBox();
  await page.mouse.move(wide.x+wide.width+2,wide.y+wide.height/2);await page.mouse.down();await page.mouse.move(300,wide.y+wide.height/2,{steps:10});await page.mouse.up();
  await page.setViewportSize({width:1100,height:760});
  const more=page.getByRole('button',{name:'More drawing tools',exact:true});await more.waitFor();
  await more.click();
  const menu=page.getByRole('menu',{name:'More drawing tools',exact:true});
  const row=menu.getByRole('menuitemcheckbox',{name:'Isometric Box',exact:true});
  const rowBox=await row.boundingBox();
  await row.click({position:{x:rowBox.width-8,y:rowBox.height/2}});
  const background=()=>more.evaluate(el=>({color:getComputedStyle(el).backgroundColor,image:getComputedStyle(el).backgroundImage}));
  assert.equal((await background()).color,'rgb(40, 169, 244)');
  assert.equal(await more.locator('svg.lucide-ellipsis').count(),1);
  await more.click();
  assert.match(await menu.locator('[data-overflow-tool="isometric"]').getAttribute('style'),/80%/);
  await menu.locator('[data-overflow-tool="isometric"]').click({button:'right'});
  assert.match((await background()).image,/linear-gradient/);
  await more.click();
  assert.match(await menu.locator('[data-overflow-tool="isometric"]').evaluate(el=>getComputedStyle(el).backgroundImage),/linear-gradient/);
  await menu.locator('[data-overflow-tool="draw-ellipse"]').click({button:'right'});
  assert.match((await background()).image,/linear-gradient/);
  assert.equal(await more.locator('svg.lucide-ellipsis').count(),1);
  await more.click();
  assert.match(await menu.locator('[data-overflow-tool="draw-ellipse"]').getAttribute('style'),/80%/);
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+b');
  await page.setViewportSize({width:1800,height:900});
  await more.waitFor({state:'hidden'});
  assert.equal(await page.locator('[data-tool="isometric"]').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(40, 169, 244)');
  assert.equal(await page.locator('[data-tool="draw-ellipse"]').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 139, 54)');
  await page.setViewportSize({width:700,height:760});
  await page.keyboard.press('Control+1');
  const narrowSidebar=page.locator('#side-panel');await narrowSidebar.waitFor();
  const narrow=await narrowSidebar.boundingBox();
  const topmost=await page.evaluate(({x,y})=>document.elementFromPoint(x,y)?.closest('#side-panel')!==null,{x:narrow.x+50,y:narrow.y+narrow.height-20});
  assert(topmost,'sidebar stays above workspace dock');
  assert.deepEqual(errors,[]);
  console.log('PASS: full-row left/right selection; 80% dropdown tints; unchanged ellipsis and icon colors; split More assignment; narrow sidebar above dock.');
 } finally {await browser.close();server.kill();}
})().catch(e=>{console.error(e);process.exit(1)});
