const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({ channel: 'chrome', headless: true });
 try {
  const context = await browser.newContext({ viewport: { width: 1200, height: 850 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', e => errors.push(e.stack)); page.setDefaultTimeout(15000);
  let fixture = fs.readFileSync('scripts/fixtures/document-workspace.js', 'utf8');
  fixture = fixture.replace('export async function call(command,args={}){', 'export async function call(command,args={}){ if(command === "read_settings_file")return sessionStorage.getItem("fixture-settings"); if(command === "write_settings_file"){sessionStorage.setItem("fixture-settings",args.json);return;} if(command === "storage_status")return {mode:"default",managed:false,paths:{config:"test-config",webview:"test-webview"}}; if(command === "prepare_storage_migration")throw new Error("Close other Pixen windows and MCP connections before changing storage mode"); if(command === "theme_config") return {files:[{file_name:"custom.json",source:{format:"json",text:JSON.stringify({version:1,id:"custom",name:"Custom test",appearance:"dark",tokens:{"frame.accent":"#123456"}})}},{file_name:"invalid.json",source:{format:"json",text:"not json"}}]}; if(command === "ai_test_provider") return [{id:"artist",label:"Artist model"}];');
  await page.route('**/src/services/backend.ts', route => route.fulfill({ contentType: 'text/javascript', body: fixture }));
  await page.route('**/@tauri-apps_api_window.js*', route => route.fulfill({ contentType: 'text/javascript', body: 'export function getCurrentWindow(){return { onDragDropEvent:async()=>()=>{}, onCloseRequested:async()=>()=>{}, close:async()=>{} };}' }));
  await page.route('**/@tauri-apps_api_event.js*', route => route.fulfill({ contentType: 'text/javascript', body: 'export async function listen(){return ()=>{}}' }));
  await page.goto(process.env.PIXEN_TEST_URL || 'http://127.0.0.1:1422');
  await page.locator('.workbench').waitFor();
  await page.waitForFunction(() => window.testCalls?.some(call => call.command === 'snapshot'));
  await page.locator('.workbench').click({ position: { x: 500, y: 100 } });
  await page.keyboard.press('Control+,');
  const dialog = page.getByRole('dialog', { name: 'Settings', exact: true }); await dialog.waitFor();
  const storageMode = dialog.getByRole('combobox', { name: 'Storage mode', exact: true });
  await storageMode.click();
  assert.deepEqual(await page.getByRole('option').allTextContents(), ['Default', 'Portable', 'Semi-portable']);
  await page.getByRole('option', { name: 'Semi-portable', exact: true }).click();
  await dialog.getByRole('button', { name: 'Apply and restart', exact: true }).click();
  await dialog.getByRole('alert').filter({hasText:'Close other Pixen windows'}).waitFor();
  await dialog.getByRole('button', { name: 'Appearance', exact: true }).click();
  const theme = dialog.getByRole('combobox', { name: 'Theme', exact: true });
 await theme.click();
 assert.deepEqual((await page.getByRole('option').allTextContents()).map(text => text.replace(/default$/, '')), ['Pixen (built-in)', 'Custom test']);
 await page.getByRole('option', { name: 'Custom test', exact: true }).click();
 assert.equal(await dialog.evaluate(el => getComputedStyle(el).getPropertyValue('--frame-accent').trim().toLowerCase()), '#123456');
 await page.waitForFunction(()=>JSON.parse(sessionStorage.getItem('fixture-settings')??'{}')['pixen.theme']==='custom');
 await theme.click();
 await page.getByRole('option', { name: /^Pixen \(built-in\)/ }).click();
 assert.equal(await dialog.evaluate(el => getComputedStyle(el).getPropertyValue('--frame-accent').trim().toLowerCase()), '#fe725e');
 await dialog.getByRole('button', { name: 'Canvas', exact: true }).click();
 const row = page.locator('[data-setting-id="pixen.background"]'); await row.hover();
  await page.getByRole('button', { name: 'More Actions for Default background', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Copy Setting ID', exact: true }).click();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'pixen.background');
  await page.getByRole('button', { name: 'AI', exact: true }).click();
  const provider = page.getByRole('combobox', { name: 'Provider', exact: true });
  assert.equal(await provider.locator('xpath=ancestor::*[contains(@class,"frame-input-group")]').count() > 0, true);
  await page.getByRole('button', { name: 'Test provider', exact: true }).click();
  await page.getByText('Provider is available.', { exact: true }).waitFor();
  const model = page.getByRole('combobox', { name: 'Model', exact: true }); await model.click();
  await page.getByRole('option', { name: 'Artist model', exact: true }).click();
  if (process.env.PIXEN_SETTINGS_SCREENSHOT) await page.screenshot({ path: process.env.PIXEN_SETTINGS_SCREENSHOT });
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+Shift+,');
  await page.getByRole('dialog', { name: 'Keyboard Shortcuts', exact: true }).waitFor();
  await page.getByRole('columnheader', { name: 'When', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('Pixen settings checks passed: enabled Frame service, populated row menu, clipboard, grouped provider test, model discovery, shortcut manager, custom-theme selection, and built-in theme restoration.');
 } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
