const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } });
    page.setDefaultTimeout(20000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const fixture = fs.readFileSync('scripts/fixtures/document-workspace.js', 'utf8')
      .replace("const path=args.path??'a.pixloom'", "const path=args.path??'animation.pixloom'")
      .replace("if(command==='desktop_ready')return;", "if(command==='choose_export_folder')return window.cancelFolder?null:'C:\\\\exports'; if(command==='export_document')return window.cancelExport?false:true; if(command==='desktop_ready')return;");
    await page.route('**/src/services/backend.ts', route => route.fulfill({ contentType: 'text/javascript', body: fixture }));
    await page.route('**/@tauri-apps_api_window.js*', route => route.fulfill({ contentType: 'text/javascript', body: 'export function getCurrentWindow(){return {onDragDropEvent:async()=>()=>{},onCloseRequested:async()=>()=>{},close:async()=>{}}}' }));
    await page.route('**/@tauri-apps_api_event.js*', route => route.fulfill({ contentType: 'text/javascript', body: 'export async function listen(){return ()=>{}}' }));
    await page.goto(process.env.PIXEN_TEST_URL || 'http://127.0.0.1:1420', { timeout: 60000, waitUntil: 'domcontentloaded' });
    await page.waitForLoadState('networkidle');
    await page.getByRole('button', { name: /Open artwork/ }).first().click();
    await page.locator('canvas.artwork').waitFor();
    await page.keyboard.press('Control+Shift+E');
    await page.getByRole('heading', { name: 'Export artwork', exact: true }).waitFor();
    const footer = page.locator('.frame-modal-footer');
    const submit = footer.getByRole('button', { name: 'Export', exact: true });
    assert.equal(await submit.isDisabled(), true);
    assert.equal(await page.locator('#pixen-export').getByRole('button', { name: 'Export', exact: true }).count(), 0);
    await page.getByLabel('File name', { exact: true }).fill('hero');
    await page.evaluate(() => window.cancelFolder = true);
    await page.getByRole('button', { name: 'Browse…', exact: true }).click();
    await page.getByRole('button', { name: 'Browse…', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Folder', { exact: true }).inputValue(), '');
    await page.evaluate(() => window.cancelFolder = false);
    await page.getByRole('button', { name: 'Browse…', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#pixen-export input[placeholder]')?.value === 'C:\\exports');
    const firstEntry = page.getByRole('region', { name: 'Export 1', exact: true });
    assert.equal(await page.locator('#pixen-export .field').count(), 0);
    assert.equal(await firstEntry.getByRole('button', {name:'Remove export 1',exact:true}).innerText(), '');
    assert.equal(await page.getByLabel('File name', {exact:true}).evaluate(element => element.classList.contains('frame-text-input')), true);
    assert.equal(await firstEntry.getByRole('spinbutton', {name:'Frame',exact:true}).evaluate(element => element.classList.contains('frame-text-input')), true);
    const margins = await firstEntry.locator('.frame-field').evaluateAll(elements => elements.map(element => [getComputedStyle(element).marginTop, getComputedStyle(element).marginBottom]));
    assert(margins.every(pair => pair[0] === '0px' && pair[1] === '0px'));
    const summaryBefore = await firstEntry.locator('.export-output-summary').boundingBox();
    const cardBefore = await firstEntry.boundingBox();
    assert.equal(await firstEntry.locator('.export-background-color').evaluate(element => getComputedStyle(element).visibility), 'hidden');
    await firstEntry.getByRole('checkbox', {name:'Use background color',exact:true}).click();
    await firstEntry.getByRole('button', {name:'Background color',exact:true}).waitFor();
    const summaryAfter = await firstEntry.locator('.export-output-summary').boundingBox();
    const cardAfter = await firstEntry.boundingBox();
    assert(Math.abs(summaryBefore.y - summaryAfter.y) < 1, 'background toggle moves output summary');
    assert(Math.abs(cardBefore.height - cardAfter.height) < 1, 'background toggle changes export section height');
    const filenameBox = await firstEntry.locator('.export-filename').boundingBox();
    const sizeBox = await firstEntry.locator('.export-pixel-size').boundingBox();
    assert(Math.max(filenameBox.y, sizeBox.y) < Math.min(filenameBox.y + filenameBox.height, sizeBox.y + sizeBox.height), 'filename and pixel dimensions are on separate rows');
    assert(Math.abs(sizeBox.x + sizeBox.width - (summaryAfter.x + summaryAfter.width)) < 1, 'pixel dimensions are not right aligned');
    await firstEntry.getByRole('button', {name:'Background color',exact:true}).click();
    await page.locator('.frame-color-picker-popover').waitFor();
    await page.keyboard.press('Escape');
    await firstEntry.getByRole('checkbox', {name:'Use background color',exact:true}).click();
    await page.locator('.frame-modal').screenshot({path:'output/export-form-refinement.png'});
    async function choose(label, value) {
      const match = /^(Export kind|Format|Arrange by) (\d+)$/.exec(label);
      const region = page.getByRole('region', {name:'Export '+match[2],exact:true});
      await region.getByRole('combobox', {name:match[1]==='Export kind'?'Export':match[1],exact:true}).click();
      await page.getByRole('option', { name: value, exact: true }).click();
    }
    await choose('Export kind 1', 'Sprite sheet');
    await page.getByRole('spinbutton', { name: 'Columns', exact: true }).fill('3');
    await page.getByRole('spinbutton', { name: 'Scale (nearest neighbor)', exact: true }).fill('2');
    await page.getByText('3 columns × 2 rows, in timeline order.', { exact: true }).waitFor();
    await page.getByRole('region', {name:'Export 1',exact:true}).getByRole('combobox', {name:'Format',exact:true}).click();
    assert.equal(await page.getByRole('option', { name: 'MP4', exact: true }).getAttribute('aria-disabled'), 'true');
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Add export', exact: true }).click();
    await choose('Format 2', 'JPEG');
    await page.getByRole('region', { name: 'Export 2', exact: true }).getByRole('button', { name: 'Background color', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Add export', exact: true }).click();
    await choose('Export kind 3', 'Video');
    assert.equal(await page.getByRole('region', {name:'Export 3',exact:true}).getByRole('combobox', {name:'Format',exact:true}).innerText(), 'MP4');
    await page.getByRole('region', {name:'Export 3',exact:true}).getByRole('combobox', {name:'Format',exact:true}).click();
    assert.equal(await page.getByRole('option', { name: 'PNG', exact: true }).getAttribute('aria-disabled'), 'true');
    await page.keyboard.press('Escape');
    await choose('Export kind 3', 'Animation');
    assert.equal(await page.getByRole('region', {name:'Export 3',exact:true}).getByRole('combobox', {name:'Format',exact:true}).innerText(), 'GIF');
    await page.getByRole('button', { name: 'Add export', exact: true }).click();
    await choose('Export kind 4', 'Editable project');
    await page.getByText('hero.pixen.json', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Add export', exact: true }).click();
    await page.getByText('hero-sheet.png', { exact: true }).waitFor();
    await page.getByText('hero-frame.png', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Remove export 5', exact: true }).click();
    await page.getByText('hero.png', { exact: true }).waitFor();
    await page.evaluate(() => window.cancelExport = true);
    await submit.click();
    await page.getByRole('heading', { name: 'Export artwork', exact: true }).waitFor();
    await page.evaluate(() => window.cancelExport = false);
    await submit.click();
    await page.getByRole('heading', { name: 'Export artwork', exact: true }).waitFor({ state: 'hidden' });
    const calls = await page.evaluate(() => window.testCalls.filter(call => call.command === 'export_document'));
    assert.equal(calls.length, 2);
    const request = calls.at(-1).args.request;
    assert.equal(request.directory, 'C:\\exports'); assert.equal(request.name, 'hero');
    assert.deepEqual(request.exports.map(entry => entry.format), ['png', 'jpeg', 'gif', 'pixen.json']);
    assert.deepEqual(request.exports.map(entry => entry.mode), ['sheet', 'frame', 'animation', 'project']);
    assert.equal(request.exports[0].gridCount, 3); assert.equal(request.exports[0].scale, 2);
    assert.deepEqual(errors, []);
    console.log('Batch export: Frame footer/selects, kind restrictions, add/remove, names, folder, parameters and cancellation passed');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
