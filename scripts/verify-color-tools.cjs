const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',args:['--no-proxy-server']});
  try {
    const page=await browser.newPage({viewport:{width:1100,height:900}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    const fixture=fs.readFileSync('scripts/fixtures/manual-tools.js','utf8').replace("if(command==='paint_pixels'){","if(command==='paint_pixels'){ if(window.rejectPaint) throw new Error('rejected paint');");
    await page.route('**/src/services/backend.ts',route=>route.fulfill({contentType:'text/javascript',body:fixture}));
    await page.route('**/@tauri-apps_api_window.js*',route=>route.fulfill({contentType:'text/javascript',body:'export function getCurrentWindow(){return {onDragDropEvent:async()=>()=>{},onCloseRequested:async()=>()=>{},close:async()=>{}}}'}));
    await page.route('**/@tauri-apps_api_event.js*',route=>route.fulfill({contentType:'text/javascript',body:'export async function listen(){return ()=>{}}'}));
    await page.goto(process.env.PIXEN_TEST_URL||'http://127.0.0.1:1459');
    await page.getByRole('button',{name:/Open artwork/}).click();
    if (!await page.locator('.color-picker').isVisible()) await page.getByRole('button',{name:'Toggle primary sidebar',exact:true}).click();
    await page.getByRole('button',{name:'Tools',exact:true}).click();
  async function selectPicker(mode){await page.getByRole('button',{name:'Color picker type',exact:true}).click();await page.getByRole('menuitemcheckbox',{name:{rectangle:'HSV Rectangle',wheel:'HSV Wheel',circle:'VHS Circle'}[mode],exact:true}).click();}
    const recent=page.getByRole('group',{name:'Recent colors'}),area=page.locator('.frame-hsv-area');
    await area.waitFor();
    assert.equal(await recent.locator('button').count(),0);
    assert(await recent.locator('.empty-recent-color').count()>3);
    assert.equal(await page.locator('.document-history').count(),0);
    assert.equal(await page.locator('.titlebar-navigation').getByRole('button',{name:'Back',exact:true}).count(),1);
    const slotBoxes=await recent.locator('.frame-color-swatch').evaluateAll(nodes=>nodes.map(el=>({x:el.getBoundingClientRect().x,right:el.getBoundingClientRect().right})));
    const rowBox=await recent.boundingBox();
    assert(slotBoxes.every(box=>box.x>=rowBox.x && box.right<=rowBox.x+rowBox.width+1));
    const plane=page.locator('.frame-hsv-plane-root .frame-color-plane'),p=await plane.boundingBox();
    const slider=await area.locator('.frame-color-slider').boundingBox();
    assert(slider.x>=p.x+p.width && slider.height>slider.width*3);
    const thumb=await area.locator('.frame-color-thumb').first().boundingBox();
    assert(Math.abs(thumb.width-thumb.height)<.1);
    await page.mouse.move(p.x+p.width*.2,p.y+p.height*.3);await page.mouse.down();
    await page.mouse.move(p.x+p.width*.7,p.y+p.height*.4,{steps:10});await page.mouse.up();
    assert.equal(await recent.locator('button').count(),0,'picker exploration must not record history');
    for(const variant of ['wheel','circle']){
      await selectPicker(variant);
      const disc=area.locator('.frame-hsv-disc'),box=await disc.boundingBox();
      assert(Math.abs(box.width-box.height)<1,'disc must remain circular');
      await disc.focus();await page.keyboard.press('ArrowRight');
      assert.equal(await recent.locator('button').count(),0);
      const marker=await area.locator('.frame-hsv-thumb').boundingBox();
      assert(Math.abs(marker.width-marker.height)<.1);
    }
    await selectPicker('rectangle');
    const art=page.locator('canvas.artwork:not(.selection-overlay)');
    await page.waitForFunction(()=>document.querySelector('canvas.artwork')?.width===16);
    async function paint(){const box=await art.boundingBox();await page.mouse.click(box.x+box.width*.4,box.y+box.height*.4);await page.waitForTimeout(180);}
    const selected=await page.getByLabel('Hex color, optional alpha').inputValue();
    await paint();
    assert.equal(await recent.locator('button').count(),1,'painting records the explored color');
    assert((await recent.locator('button').first().getAttribute('aria-label')).includes('#'+selected.slice(0,6)));
    await page.getByRole('button',{name:'Back',exact:true}).click();
    await page.waitForTimeout(100);
    assert(await page.evaluate(()=>window.toolPixels().every(v=>v===0)));
    await page.getByRole('button',{name:'Forward',exact:true}).click();await page.waitForTimeout(100);
    assert(await page.evaluate(()=>window.toolPixels().some(v=>v!==0)));
    const hex=page.getByLabel('Hex color, optional alpha');
    await hex.fill('aabbcc80');await hex.press('Tab');
    assert.equal(await recent.locator('button').count(),2);
    assert.equal(await recent.locator('button').first().getAttribute('aria-label'),'Use recent color #aabbcc80');
    const swatchBackground=await recent.locator('button .frame-color-swatch').first().evaluate(el=>getComputedStyle(el).backgroundColor);
    assert(swatchBackground.includes('170, 187, 204'),'Frame swatch must display its bound color');
    await recent.locator('button').last().click();assert((await hex.inputValue()).startsWith(selected.slice(0,6)));
    // Exploration followed by a rejected edit must not enter recent colors.
    await plane.click({position:{x:p.width*.6,y:p.height*.3}});
    await page.evaluate(()=>window.rejectPaint=true);await paint();
    assert.equal(await recent.locator('button').count(),2);
    await page.evaluate(()=>window.rejectPaint=false);
    await selectPicker('circle');
    await page.setViewportSize({width:850,height:900});
    const narrow=await area.locator('.frame-hsv-disc').boundingBox();assert(Math.abs(narrow.width-narrow.height)<1);
    await selectPicker('rectangle');

    await page.getByRole('tab',{name:'Linear',exact:true}).click();
    await page.getByLabel('Red value',{exact:true}).fill('0.5');await page.getByLabel('Red value',{exact:true}).press('Tab');
    assert((await hex.inputValue()).startsWith('bc'),'linear 0.5 converts to sRGB 188');
    await page.evaluate(()=>{const block=document.createElement('button');block.id='sample-ui';block.textContent='sample';block.style.cssText='position:fixed;right:10px;top:70px;width:60px;height:60px;background:rgb(18,52,86);z-index:9000';block.onclick=()=>window.sampleClicked=true;document.body.append(block);});
    await page.locator('.tool-grid [data-tool=eyedropper]').click({button:'right'});
    const artBox=await art.boundingBox();
    await page.mouse.move(artBox.x+artBox.width*.4,artBox.y+artBox.height*.4);
    assert.equal(await page.locator('.color-sampler').count(),0,'toolbar picker must not create a magnifier');
    assert(await page.locator('.tool-cursor [data-slot=right]').count()>0,'toolbar picker keeps its pixel outline');
    await page.mouse.click(artBox.x+artBox.width*.4,artBox.y+artBox.height*.4,{button:'right'});await page.waitForTimeout(150);
    assert((await page.getByRole('button',{name:/^secondary color/}).getAttribute('aria-label')).includes(selected.slice(0,6)));
    const paintsBefore=await page.evaluate(()=>window.testCalls.filter(c=>c.command==='paint_pixels').length);
    await page.keyboard.down('Alt');await page.mouse.move(810,90);
    await page.getByRole('status',{name:'Color sampler preview',exact:true}).waitFor();
    await page.waitForFunction(()=>document.querySelector('.color-sampler')?.getAttribute('data-color')==='#123456');
    const cursor=await page.evaluate(()=>getComputedStyle(document.body).cursor);
    assert(cursor.includes('data:image/png')&&cursor.includes('29 29'),'magnifier replaces the cursor at its sample hotspot');
    const lens=await page.locator('.color-sampler canvas').evaluate(canvas=>{
      const ctx=canvas.getContext('2d');return {width:canvas.width,height:canvas.height,bar:[...ctx.getImageData(29,67,1,1).data],border:[...ctx.getImageData(29,0,1,1).data],divider:[...ctx.getImageData(29,58,1,1).data]};
    });
    assert.deepEqual(lens.bar,[18,52,86,255]);assert.deepEqual(lens.border,lens.divider);
    assert.equal(await page.locator('.color-sampler').textContent(),'','no color-code caption');
    await page.mouse.down();await page.mouse.move(815,95);await page.mouse.up();await page.keyboard.up('Alt');
    assert.equal(await hex.inputValue(),'123456');
    assert.equal(await page.locator('.color-sampler').count(),0);
    assert.equal(await page.evaluate(()=>window.sampleClicked),undefined);
    assert.equal(await page.evaluate(()=>window.testCalls.filter(c=>c.command==='paint_pixels').length),paintsBefore);
    assert(await page.locator('.tool-grid [data-tool=pencil]').evaluate(el=>el.classList.contains('assigned-left')));
    await page.evaluate(()=>{const color=getComputedStyle(document.querySelector('.workbench-layout')).getPropertyValue('--frame-accent').trim();document.querySelector('#sample-ui').style.background=color;return color;});
    await page.keyboard.down('Alt');await page.mouse.move(810,90);
    await page.waitForFunction(()=>{const c=document.querySelector('.color-sampler canvas');if(!c)return false;const x=c.getContext('2d');const border=x.getImageData(29,0,1,1).data,bar=x.getImageData(29,67,1,1).data;return border[0]!==bar[0]||border[1]!==bar[1]||border[2]!==bar[2];});
    const rounded=await page.locator('.color-sampler canvas').evaluate(canvas=>{const ctx=canvas.getContext('2d');return {corner:ctx.getImageData(0,0,1,1).data[3],border:[...ctx.getImageData(29,0,1,1).data],bar:[...ctx.getImageData(29,67,1,1).data],url:canvas.toDataURL()};});
    assert(rounded.corner<255,'rounded corner must be transparent');
    assert(rounded.border.slice(0,3).every(v=>v===0)||rounded.border.slice(0,3).every(v=>v===255),'near-accent sample uses a contrast border');
    fs.writeFileSync('target/ui-verification/rounded-sampler.png',Buffer.from(rounded.url.split(',')[1],'base64'));
    await page.keyboard.up('Alt');
    await page.keyboard.down('Alt');await page.mouse.move(810,90);await page.keyboard.press('Escape');await page.keyboard.up('Alt');
    assert.equal(await page.locator('.color-sampler').count(),0);
    await page.evaluate(()=>document.querySelector('#sample-ui').remove());
    await page.locator('.tool-grid [data-tool=eraser]').click({button:'right'});
    await page.getByRole('button',{name:/^Left tools/}).click();
    await page.getByRole('button',{name:/^Right tools/}).click();
    await page.getByRole('button',{name:'Dismiss error',exact:true}).click();
    await page.locator('.color-picker').scrollIntoViewIfNeeded();
    fs.mkdirSync('target/ui-verification',{recursive:true});await page.screenshot({path:'target/ui-verification/frame-color-tools.png'});
    assert.deepEqual(errors,[]);
    console.log('PASS: intentional color history, empty width-fitting Frame swatches, round HSV areas and thumbs, vertical slider, title-bar canvas undo/redo, and rejected edits.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1)});
